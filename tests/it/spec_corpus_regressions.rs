/// **Question.** Are the shapes the checklist calls "not allowed" rejected?
///
/// **Three are not**, and each is accepted both standalone and inside an allele,
/// then emitted again unchanged — so the prohibition is enforced on neither the
/// input nor the output side.
///
/// The clauses, verbatim:
///
/// - `checklist.md:33` — "Describing a variant as `c.5439_5430ins6` is not
///   allowed, the inserted sequence (for `ins6`, e.g., `TGCCAT`) should be
///   specified." Ferro *does* reject `ins6` when the two anchors are not adjacent
///   (per `DNA/insertion.md:15`), which is a different check that happens to
///   catch the spec's own example; with adjacent anchors nothing fires.
/// - `checklist.md:16` — a genomic reference "can not have nucleotides with
///   additions like a `+`, `-`, or `*`".
/// - `checklist.md:45` — "Not correct is `c.12-14del`, this describes a deletion
///   of nucleotide -14 in the intron directly 5' of nucleotide `c.12`". On a
///   genomic axis there is no intron to read it into, so the shape has no legal
///   reading at all.
#[test]
fn absolute_prohibitions_are_accepted_and_re_emitted() {
    let core = at_core();
    let coding = Frame::build(RefShape::CodingSingleExon, &core);
    let genomic = Frame::build(RefShape::Genomic, &core);

    // `ins6`: an insertion that states a LENGTH instead of a sequence.
    assert_eq!(
        normalize_3prime(&coding, "NM_TEST.1:c.10_11ins6"),
        "NM_TEST.1:c.10_11ins6",
        "PINNED DEFECT — checklist.md:33 says an insertion sized by a number 'is not allowed, \
         the inserted sequence … should be specified'. Correct behaviour: refuse."
    );

    // A `+` offset on a genomic axis, which has no introns to hang one off.
    assert_eq!(
        normalize_3prime(&genomic, "NC_TEST.1:g.266+2del"),
        "NC_TEST.1:g.266+2del",
        "PINNED DEFECT — checklist.md:16 says a `g.` reference 'can not have nucleotides with \
         additions like a `+`, `-`, or `*`'. Correct behaviour: refuse."
    );

    // A hyphen where the range separator belongs.
    assert_eq!(
        normalize_3prime(&genomic, "NC_TEST.1:g.266-268del"),
        "NC_TEST.1:g.266-268del",
        "PINNED DEFECT — checklist.md:45 calls the hyphen form 'Not correct', and on a genomic \
         axis it has no intronic reading either. Correct behaviour: refuse."
    );
}

/// **Question.** Does a prohibited member become *less* visible when it sits
/// inside an allele?
///
/// **This one does, and that is the more interesting half.** The three shapes
/// above are accepted standalone, so an allele containing one is unsurprising —
/// but it matters that the allele form is checked, because a hygiene check that
/// runs once per description rather than once per member is a failure mode with
/// its own signature, and the corpus generates both forms of every prohibition
/// precisely to tell them apart.
///
/// Note the reordering: ferro sorts members by position, so the offending member
/// moves. That is the 3' rule doing its job and is not the defect.
#[test]
fn a_prohibited_member_inside_an_allele_is_also_accepted() {
    let core = at_core();
    let coding = Frame::build(RefShape::CodingSingleExon, &core);
    assert_eq!(
        normalize_3prime(&coding, "NM_TEST.1:c.[10_11ins6;9del]"),
        "NM_TEST.1:c.[9del;10_11ins6]",
        "PINNED DEFECT — see `absolute_prohibitions_are_accepted_and_re_emitted`; the allele \
         form is pinned separately so a per-description-only fix is visible as a partial one."
    );
}

/// **Question.** Is `X` a nucleotide?
///
/// **No.** `background/standards.md` lists it in the DNA symbol table and then
/// footnotes it at `:39` — "† used in alignment only" — alongside `-`. So neither
/// is a base a description may state. Ferro rejects `-` (the parser stops at it)
/// and accepts `X`.
///
/// Classified `conditional` rather than `absolute` in the corpus, because the
/// footnote states a scope rather than using prohibitive words. It is pinned as a
/// finding to adjudicate, not asserted as a regression.
#[test]
fn an_alignment_only_x_base_is_accepted_as_a_nucleotide() {
    let core = at_core();
    let coding = Frame::build(RefShape::CodingSingleExon, &core);
    assert_eq!(
        normalize_3prime(&coding, "NM_TEST.1:c.10delinsX"),
        "NM_TEST.1:c.10delinsX",
        "PINNED FINDING — standards.md:39 footnotes `X` as 'used in alignment only'. Whether \
         that is a refusal is an adjudication; what is not in doubt is that `X` is not one of \
         the 15 symbols a description may state."
    );
    // The sibling symbol IS rejected, which is what makes the pair worth pinning
    // together: the two are footnoted identically and treated differently.
    assert!(
        parse_hgvs("NM_TEST.1:c.10delins-").is_err(),
        "`-` is rejected while `X` is accepted, though standards.md:39 footnotes both"
    );
}

/// **Question.** May an intronic position be written against a bare transcript
/// accession?
///
/// **No.** `checklist.md:20`: "NM reference sequences cover mature transcripts and
/// **do not contain** intron and gene flanking sequences, and can only be used to
/// describe variants in introns using a `c.` prefix when a genomic reference
/// sequence is given on which the coding DNA reference sequence is annotated,
/// e.g., `NC_000023.10(NM_004006.2):c.94-2A>G` or `LRG_199t1:c.94-2A>G`."
///
/// Ferro accepts the bare form. This is why the corpus writes its intronic
/// idempotency rows against `NC_SYNTH.1(NM_TEST.1)` and generates the bare form
/// only as a shape that ought to be refused: a bare `NM_…:c.123+65del` is an
/// **invalid input**, not a test case.
#[test]
fn a_bare_transcript_accession_accepts_an_intronic_position() {
    let core = at_core();
    let frame = Frame::build(RefShape::CodingMultiExon(Strand::Plus), &core);
    assert_eq!(
        normalize_3prime(&frame, "NM_TEST.1:c.20+2del"),
        "NM_TEST.1:c.20+2del",
        "PINNED FINDING — checklist.md:20 permits an intronic `c.` position only with a genomic \
         wrapper. Correct behaviour: refuse, or demand the NC_(NM_) form."
    );
    // The wrapper form is what the spec asks for, and ferro accepts it too — so
    // the fix is a refusal of the bare form, not support for the wrapper.
    assert!(parse_hgvs("NC_SYNTH.1(NM_TEST.1):c.20+2del").is_ok());
}

