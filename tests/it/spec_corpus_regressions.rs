/// **Question.** Is an insertion at the CDS/3'UTR boundary a fixed point?
///
/// **No.** `c.*1delinsCTT` normalizes to `c.72_*1insCT`, which normalizes again to
/// `c.72delinsCCT`. Idempotency is not a spec clause — it is an invariant of any
/// normalizer, and `FERRO_ASSERT_IDEMPOTENT` exists to police it — so this is
/// pinned as a defect with no citation to make.
///
/// The shape needs a transcript with a real 3'UTR, which a `CDS_START = 1`
/// single-exon fixture cannot have (#1478). It reproduces on both strands.
#[test]
fn an_insertion_at_the_cds_end_is_not_a_fixed_point() {
    let core = acgt_core();
    for strand in [Strand::Plus, Strand::Minus] {
        let frame = Frame::build(RefShape::CodingMultiExon(strand), &core);
        let once = normalize_3prime(&frame, "NM_TEST.1:c.*1delinsCTT");
        assert_eq!(once, "NM_TEST.1:c.72_*1insCT");
        let twice = normalize_3prime(&frame, &once);
        assert_eq!(
            twice, "NM_TEST.1:c.72delinsCCT",
            "PINNED DEFECT — normalization must be idempotent. `{once}` is not its own fixed \
             point on the {strand:?} strand."
        );
    }
}

/// **Question.** What does a deletion flush against an insertion at the CDS/3'UTR
/// boundary denote, and does ferro preserve it?
///
/// **It does not.** `c.[72del;72_*1insA]` deletes the last CDS base and inserts
/// `A` at the interbase immediately 3' of it, which denotes
/// `…tx[..83] + "A" + tx[84..]` — the same sequence as `c.72delinsA`. Ferro
/// returns `c.[72delinsTA;*2del]`, which denotes different bases: it keeps a base
/// the input deleted and deletes one the input did not touch.
///
/// **Sequence preservation is the one property no representation argument can
/// excuse**, so this is the most serious of the four rows in its class. It is a
/// `CoincidentEndpoint` geometry — two members sharing an endpoint without their
/// footprints intersecting — which is legal, and which the designed corpus could
/// not build before #1456.
///
/// Honest caveat, recorded rather than glossed: the corpus's applier reads a
/// deletion and a flush insertion in one order (longer deletion first, then the
/// zero-width member), and one *could* argue an insertion anchored on a base the
/// same allele deletes is itself ill-defined. If that reading wins, the fix is a
/// refusal rather than a different output — but it cannot be the output ferro
/// gives, which denotes a third sequence that neither reading produces.
#[test]
fn a_deletion_flush_against_an_insertion_at_the_cds_end_changes_the_sequence() {
    let core = at_core();
    for strand in [Strand::Plus, Strand::Minus] {
        let frame = Frame::build(RefShape::CodingMultiExon(strand), &core);
        let input = "NM_TEST.1:c.[72del;72_*1insA]";
        let expected = match denotation_of(frame.provider(), frame.served(), input) {
            Denotation::Sequence(sequence) => sequence,
            other => panic!("the input must denote a sequence, got {other:?}"),
        };
        let output = normalize_3prime(&frame, input);
        assert_eq!(
            output, "NM_TEST.1:c.[72delinsTA;*2del]",
            "PINNED DEFECT on the {strand:?} strand"
        );
        assert_ne!(
            denotation_of(frame.provider(), frame.served(), &output),
            Denotation::Sequence(expected),
            "if this now holds, the defect is FIXED — move the assertion above to the \
             sequence-preserving output and re-bless the axis census in the same commit"
        );
    }
}

