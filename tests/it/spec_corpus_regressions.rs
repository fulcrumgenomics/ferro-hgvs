/// **Question.** Does ferro implement rejected proposal SVD-WG010 — a separation
/// floor of two on an axis with no reading frame?
///
/// **No, and this pins that.** `general.md:36-39` announces a "new
/// recommendation" that "two variants separated by less than two nucleotides
/// should be described as a 'delins'". That note is **stale**: it describes
/// SVD-WG010, opened 2021-05-15 and closed **rejected** 2021-07-31
/// (`consultation/SVD-WG010.md:8`, "The proposal has been **rejected**"). The live
/// rule is `general.md:34`'s floor of one, with `:35`'s codon exception — which
/// cannot reach a frameless axis at all, being conditioned on "together affecting
/// one amino acid".
///
/// This is not hypothetical: `coalesce_coding_frame_separation` once applied the
/// floor of two on a frameless axis and emitted SVD-WG010's own worked example.
/// The corpus measures **0 violations over 210 rows carrying the shape**, and the
/// denominator is asserted non-zero — `0 of 0` is what a rebuilt #1456 looks like.
///
/// Recorded per `CLAUDE.md`'s "record what was refuted, not only what was
/// decided": a measurement that killed a plausible belief is worth as much as the
/// ruling, because the belief recurs.
#[test]
fn a_frameless_irreducible_separation_of_one_is_not_merged() {
    let core = acgt_core();
    let genomic = Frame::build(RefShape::Genomic, &core);
    let served = genomic.served();

    // Two substitutions separated by one unchanged base. A substitution cannot
    // shift, so the separation is irreducible by construction — which is the
    // condition that distinguishes rejected SVD-WG010 from the 3' rule closing a
    // gap inside a run.
    let first = genomic.label(genomic.core_offset() + 8);
    let third = genomic.label(genomic.core_offset() + 10);
    let base_at = |offset: usize| &served[genomic.core_offset() + offset..][..1];
    let alt = |base: &str| if base == "A" { "C" } else { "A" };
    let input = format!(
        "NC_TEST.1:g.[{first}{}>{};{third}{}>{}]",
        base_at(8),
        alt(base_at(8)),
        base_at(10),
        alt(base_at(10))
    );

    let output = normalize_3prime(&genomic, &input);
    let parsed = parse_hgvs(&output).expect("the output re-parses");
    let members = match &parsed {
        ferro_hgvs::HgvsVariant::Allele(allele) => allele.variants.len(),
        _ => 1,
    };
    assert!(
        members >= 2,
        "merging {input} into `{output}` would implement REJECTED SVD-WG010; general.md:34 \
         says two variants separated by one or more nucleotides are described individually"
    );
}

