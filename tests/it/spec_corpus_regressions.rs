/// **Question.** Must a description whose members claim the same reference
/// territory be refused?
///
/// **Yes — it denotes no sequence.** `general.md:58`: "descriptions removing part
/// of a reference sequence and replacing it with part of the same sequence are not
/// allowed (e.g., `NM_004006.2:c.[762_768del;767_774dup]`)". Ferro already
/// enforces exactly that spelling — a `del` plus an overlapping `dup` is rejected
/// at parse with "Self-cancelling allele" — but the check is keyed on that pair of
/// edit types, so a `del` plus an overlapping `del` sails through.
///
/// Three geometries, all accepted, **72 rows in total**. Every one of them was
/// structurally impossible to generate before #1456: the designed corpus paired
/// members on disjoint territory only, and reported `0 of 18,432` three times.
#[test]
fn conflicting_member_geometries_are_normalized_instead_of_refused() {
    let core = at_core();
    let frame = Frame::build(RefShape::CodingSingleExon, &core);
    let served = frame.served();

    for (geometry, input) in [
        // One member's footprint strictly inside another's.
        ("nested", "NM_TEST.1:c.[9_12del;10_11del]"),
        // Footprints that partially intersect.
        ("overlapping", "NM_TEST.1:c.[9_12del;11_14del]"),
        // Two pure insertions at one interbase, which have no order.
        ("coincident insertions", "NM_TEST.1:c.[8_9insAC;8_9insCC]"),
    ] {
        // First, the premise: the input really does denote no sequence. Without
        // this the test would be asserting a preference rather than a defect.
        assert_eq!(
            denotation_of(frame.provider(), served, input),
            Denotation::NoSequence,
            "{geometry}: {input} must denote no sequence for this test to mean anything"
        );

        // The defect: ferro accepts it and hands back a description.
        let output = normalize_3prime(&frame, input);
        assert_eq!(
            output, input,
            "PINNED DEFECT ({geometry}) — general.md:58 makes a description that claims one \
             territory twice invalid, and ferro already rejects the del+dup spelling the clause \
             names. Correct behaviour: refuse."
        );
    }
}

