//! Named regression tests promoted out of the exhaustive spec corpus.
//!
//! # Why these exist separately from the corpus
//!
//! **A corpus row can silently stop being generated.** That is this repository's
//! recorded blindness class, three times over: #1456 (every family paired members
//! on disjoint territory, so no conflicting allele existed and `0 of 18,432` was
//! reported three times as evidence), #1460 (20-mer cores, so nothing reached
//! `MAX_SPLIT_BLOCK` and a length-gated change was structurally invisible), #1478
//! (`Exon::with_genomic(1, 1, tx_len, …)` builds ONE exon with `CDS_START = 1`, so
//! no row could cross a junction or sit in the 5'UTR). Each was invisible to the
//! one before it.
//!
//! A named committed test cannot be un-generated by a later edit to the
//! generator. So: **the corpus for breadth, these for anything that ever went
//! red.**
//!
//! # These pin DEFECTS, not answers
//!
//! Every expectation below is what ferro produces on `main` at 35de96c8, and in
//! most cases it is **wrong**. Each test states the question, the answer the cited
//! clause gives, and what ferro does instead — the `KNOWN_DIVERGENT_INPUTS`
//! pattern, which exists so a deviation stays visible rather than rotting into an
//! assumption. When one is fixed, the assertion moves to the correct value in the
//! same commit and the comment says so.
//!
//! Not fixed here on purpose: a PR that both built this instrument and changed the
//! normalizer would have no baseline to measure the change against.

use ferro_hgvs::conformance::spec_corpus::{
    corpus_cores, denotation_of, Denotation, Frame, RefShape, DENSE_CORE_LEN,
};
use ferro_hgvs::reference::transcript::Strand;
use ferro_hgvs::{parse_hgvs, NormalizeConfig, Normalizer, ShuffleDirection};

/// The `AT`-alphabet core the corpus draws first. Chosen because a two-letter
/// alphabet makes long runs, which is where junction-crossing shifts live.
fn at_core() -> String {
    corpus_cores(1, DENSE_CORE_LEN).remove(0)
}

/// The `ACGT`-alphabet core, for rows whose defect needs a non-degenerate
/// neighbourhood.
fn acgt_core() -> String {
    corpus_cores(1, DENSE_CORE_LEN).remove(1)
}

/// Normalize `input` against `frame`, in the given direction.
fn normalize(frame: &Frame, input: &str, direction: ShuffleDirection) -> String {
    let variant = parse_hgvs(input).unwrap_or_else(|e| panic!("{input} must parse: {e}"));
    let normalizer = Normalizer::with_config(
        frame.provider().clone(),
        NormalizeConfig::default().with_direction(direction),
    );
    normalizer
        .normalize(&variant)
        .unwrap_or_else(|e| panic!("{input} must normalize: {e}"))
        .to_string()
}

/// Normalize in the default (3') direction.
fn normalize_3prime(frame: &Frame, input: &str) -> String {
    normalize(frame, input, ShuffleDirection::ThreePrime)
}

// ---------------------------------------------------------------------------
// The 3' shift crosses an exon junction on a MINUS-strand transcript
// ---------------------------------------------------------------------------

/// **Question.** May the 3' shift move a deletion out of an exon and into the
/// following intron?
///
/// **Yes — the shift is legal. It is the ACCESSION that is not.** This doc
/// comment previously said "the clauses say no, twice" and cited `general.md:44`
/// as forbidding the shift. That was backwards, and it mattered: it named a
/// target that would implement an exception the spec explicitly withholds.
///
/// `general.md:44` defers to `background/numbering.md`, which scopes its
/// exception twice — `:23` applies it to **exon/exon** junctions "where shifting
/// the variant 3' would place it in the **next exon**", and `:26` states that it
/// "**does not apply** to a deletion/duplication around **exon/intron and
/// intron/exon** junctions". This row is exactly the exon→intron case `:26`
/// excludes, and ferro already blocks the exon→exon case the exception covers.
///
/// What IS violated is `checklist.md:20`: "NM reference sequences cover mature
/// transcripts and **do not contain** intron and gene flanking sequences, and can
/// only be used to describe variants in introns using a `c.` prefix when a
/// genomic reference sequence is given". So the output names a position its own
/// accession cannot express. Converging on the clamped `c.20del` would revert
/// #670; the live candidates are re-parenting onto a genomic wrapper, or refusal.
///
/// **The strand is a confound, not a finding.** The plus/minus difference below
/// is real but is a property of the fixture: the provider writes a literal
/// `GATTACA` intron and reverse-complements only the exon blocks, so against an
/// `AT` core `G` never continues a run and `AA` always does. Hold the
/// transcript-direction intron fixed and both strands agree — see
/// `defect_371_transcript_exit.rs`, whose `junction_provider` takes the intron as
/// a parameter for precisely this reason.
///
/// This is the largest single class the corpus found — **371 outputs on the 3'
/// direction and 0 on the 5'** — and it is structurally invisible to a
/// single-exon fixture, which is #1478 exactly. The 0 at 5' is a claim about the
/// code, not the corpus: all three copies of the #670 gate are guarded on
/// `ThreePrime` with no 5' mirror.
#[test]
fn a_minus_strand_junction_shift_leaves_the_transcript() {
    let core = at_core();
    let plus = Frame::build(RefShape::CodingMultiExon(Strand::Plus), &core);
    let minus = Frame::build(RefShape::CodingMultiExon(Strand::Minus), &core);

    // The contrast, NOT the target: on the plus strand the shift stops inside
    // the exon. That is a property of this fixture's intron, not a clamp the
    // minus strand is failing to apply — see the doc comment.
    assert_eq!(
        normalize_3prime(&plus, "NM_TEST.1:c.17del"),
        "NM_TEST.1:c.20del",
        "the plus-strand contrast: same design, intron that does not continue the run"
    );

    // The defect: on the minus strand it walks two bases into the intron.
    assert_eq!(
        normalize_3prime(&minus, "NM_TEST.1:c.17del"),
        "NM_TEST.1:c.20+2del",
        "PINNED DEFECT — the SHIFT is legal (numbering.md:26 withholds general.md:44's \
         exception from exon/intron junctions); what is invalid is the ACCESSION, since \
         checklist.md:20 forbids a bare NM_ from naming an intronic position. The target is \
         therefore a genomic wrapper or a refusal — NOT c.20del, which would implement an \
         exception the spec explicitly excludes and would revert #670."
    );
}

/// **Question.** What happens when *two* members of one allele both shift past
/// the same junction?
///
/// **They land on the same base.** `c.[20del;17del]` becomes
/// `c.[20+2del;20+2del]` — two identical members, which denotes no sequence at
/// all: the second deletion has nothing left to delete. `general.md:58`'s
/// neighbourhood is the closest clause ("descriptions removing part of a
/// reference sequence and replacing it with part of the same sequence are not
/// allowed"), but the plainer statement is that a description must denote one
/// sequence, and this one denotes none.
///
/// Kept separate from the single-member case because it is a *different* failure:
/// the single-member output is expressible-but-prohibited, this one is
/// self-contradictory, and only a multi-member allele can produce it.
#[test]
fn two_members_shifting_past_one_junction_collide_into_identical_members() {
    let core = at_core();
    let minus = Frame::build(RefShape::CodingMultiExon(Strand::Minus), &core);

    let output = normalize_3prime(&minus, "NM_TEST.1:c.[20del;17del]");
    assert_eq!(
        output, "NM_TEST.1:c.[20+2del;20+2del]",
        "PINNED DEFECT — two identical members denote no sequence. Correct output: \
         NM_TEST.1:c.19_20del, which is what the plus-strand control gives."
    );

    // The plus-strand control, so the strand-specificity is pinned too and a
    // future fix cannot quietly break the side that works.
    let plus = Frame::build(RefShape::CodingMultiExon(Strand::Plus), &core);
    assert_eq!(
        normalize_3prime(&plus, "NM_TEST.1:c.[20del;17del]"),
        "NM_TEST.1:c.19_20del"
    );
}

