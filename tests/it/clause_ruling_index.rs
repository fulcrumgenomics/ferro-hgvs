/// index misses is a clause a reader can look up and be told nothing about.
///
/// The second half is what keeps the first from being circular. Checking
/// `build_index()` against the same `expand()` over the same records can only
/// catch a bug in the insertion — a key collapsed, a claim overwritten. It says
/// nothing about what a human actually sees. So each key is also required to
/// appear in the text embedded in this module's docs, which is the thing the
/// `grep` in those docs will hit.
#[test]
fn every_cited_clause_appears_in_the_index() {
    let index = build_index();
    let embedded = embedded_index();
    let mut missing: Vec<String> = Vec::new();
    let mut unrendered: Vec<String> = Vec::new();
    for record in rulings::records() {
        for citation in &record.citations {
            for key in expand(&citation.clause) {
                let found = index.get(&key).is_some_and(|claims| {
                    claims
                        .iter()
                        .any(|c| c.id == record.id && c.status == record.status)
                });
                if !found {
                    missing.push(format!(
                        "{key} (cited as {} by {} / {})",
                        citation.clause, record.id, record.status
                    ));
                }
                let key_line = key.to_string();
                if !embedded
                    .lines()
                    .any(|l| l == key_line || l == format!("{key_line}  [MULTI]"))
                {
                    unrendered.push(key_line);
                }
            }
        }
    }
    assert!(
        missing.is_empty(),
        "these clause lines are named by a record but absent from the index:\n  {}\n\nfull index \
         as computed:\n{}",
        missing.join("\n  "),
        render_index()
    );
    assert!(
        unrendered.is_empty(),
        "these clause lines are in the computed index but not in the block embedded in this \
         module's docs, so a reader grepping for them finds nothing:\n  {}",
        unrendered.join("\n  ")
    );
}

/// **Multiply-named clauses are surfaced**, and the mixed-verdict ones are
/// called out separately.
///
/// The clause line below is the one this project has re-derived from spec text
/// at least four times; see `tests/it/delins_equal_vs_unequal_length_hermetic.rs`
/// for the pinned rows. It is asserted by name so that a ledger edit which drops
/// either record from it has to be argued rather than merged quietly.
#[test]
fn clauses_named_by_several_records_are_flagged() {
    let index = build_index();
    let multi: Vec<(&ClauseLine, &BTreeSet<Claim>)> =
        index.iter().filter(|(_, c)| c.len() > 1).collect();
    assert_eq!(
        multi.len(),
        26,
        "measured count of multiply-named clause lines changed; update the module docs with it"
    );

    let mixed: Vec<String> = multi
        .iter()
        .filter(|(_, claims)| {
            claims
                .iter()
                .map(|c| &c.status)
                .collect::<BTreeSet<_>>()
                .len()
                > 1
        })
        .map(|(key, _)| key.to_string())
        .collect();
    assert_eq!(
        mixed.len(),
        7,
        "measured count of mixed-verdict clause lines changed: {mixed:?}"
    );

    let key = ClauseLine {
        file: "docs/recommendations/DNA/delins.md".to_string(),
        line: 17,
    };
    let claims = index
        .get(&key)
        .unwrap_or_else(|| panic!("{key} is not in the index"));
    let ids: BTreeSet<&str> = claims.iter().map(|c| c.id.as_str()).collect();
    assert!(
        ids.contains("delins-merge-vs-individual-gap-two-or-more"),
        "{key} must resolve to the record that governs it: {ids:?}"
    );
    assert!(
        ids.contains("separation-is-a-property-of-the-spelling-not-of-the-variant"),
        "{key} must also resolve to the record that frames it as spelling-relative: {ids:?}"
    );

    // The canonical MIXED-verdict line has now moved twice, for the same reason
    // both times: the line stopped carrying a spread because the record that
    // supplied its `undecided` half got decided. `delins.md:17` lost it when
    // `separation-is-a-property-of-the-spelling-not-of-the-variant` was decided,
    // and `delins.md:18` lost it here, when `codon-carve-out-shape-restriction`
    // was. That is the expected direction of travel — the ledger is being burned
    // down — so this assertion is a moving target BY DESIGN and re-pointing it is
    // the correct maintenance, not a workaround.
    //
    // **The direction of travel is not monotonic, and `delins.md:17` is the
    // counter-example.** It is mixed AGAIN, because
    // `delins-recommendation-reach-when-the-input-arrives-split` was filed
    // against it (and against `:47`, and `general.md:34`, and
    // `open-issues.md:77-78`) as `undecided` — five lines gained a spread from
    // one new record, taking the measured `mixed` count from two to seven. So a
    // line can re-acquire a spread by a record being FILED, not only lose one by
    // a record being decided, and the burn-down framing above describes only the
    // decided half. Do not read a rise in this count as a regression: filing an
    // honest `undecided` record is what the ledger is for.
    //
    // It is pointed at a ring line rather than another `delins` one deliberately.
    // `complex.md:127` is cited by two records whose verdicts differ — and note
    // each is named on its own line below, because `ruling_citation_currency`
    // reads a status word and a record id sharing one line as a claim about that
    // record, so naming both verdicts beside both ids reads as a contradiction:
    //
    //   - `self-cancelling-across-ring-junctions` is decided.
    //   - `ring-telomere-anchoring` is undecided (added by #1595).
    //
    // That pair is the *reason* the mixed-verdict section exists — one clause
    // whose ring question is settled and whose anchoring question explicitly is
    // not. It is also the more durable choice: the two `delins` lines each had a
    // single open record standing between them and being settled, whereas
    // `ring-telomere-anchoring` is recorded as undecided on the grounds that
    // deciding it would legislate from two worked examples.
    //
    // If this fires again, the fix is to re-point it at whatever line the
    // measured `mixed` set above still contains — and if that set is ever EMPTY,
    // do not delete the assertion: an empty mixed-verdict section means the
    // rendering has nothing left to exercise, which is a fact worth failing on.
    let mixed_key = ClauseLine {
        file: "docs/recommendations/DNA/complex.md".to_string(),
        line: 127,
    };
    let mixed_claims = index
        .get(&mixed_key)
        .unwrap_or_else(|| panic!("{mixed_key} is not in the index"));
    assert!(
        mixed_claims
            .iter()
            .map(|c| &c.status)
            .collect::<BTreeSet<_>>()
            .len()
            > 1,
        "{mixed_key} is the canonical mixed-verdict clause line and must render in that section"
    );
}

/// The rendered index in this module's docs matches the ledger.
///
/// Failing prints the whole block to paste, so bringing it back into line is a
/// copy. The docs are the artifact a reader finds; a stale artifact is the same
/// failure this file is about, one level up.
#[test]
fn the_rendered_index_is_current() {
    let rendered = render_index();
    let embedded = embedded_index();
    assert!(
        !embedded.trim().is_empty(),
        "no index block found between the markers in {SELF_RELATIVE_PATH} — the extractor or the \
         markers moved"
    );
    if rendered.trim_end() != embedded.trim_end() {
        let block: String = rendered
            .lines()
            .map(|l| {
                if l.is_empty() {
                    "//!".to_string()
                } else {
                    format!("//! {l}")
                }
            })
            .collect::<Vec<_>>()
            .join("\n");
        panic!(
            "the index in this module's docs is stale. Replace everything between\n  \
             {BEGIN_MARKER}\nand\n  {END_MARKER}\n(keeping the ```text fences) with:\n\n{block}\n"
        );
    }
}
