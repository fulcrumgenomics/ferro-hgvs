//! Spec clause -> the adjudication record(s) that already govern it.
//!
//! # The failure mode this exists for
//!
//! The single most-repeated mistake in this project's history is re-deriving a
//! *settled* question from spec text. Someone opens `DNA/delins.md`, reads
//! `:17`, forms a view, and acts on it — and the ledger has had an answer for
//! that clause the whole time. `delins.md:17` against `:47` has gone round at
//! least four times on exactly that path.
//!
//! `ruling_citation_currency.rs` catches the reverse direction: prose that
//! claims a settled record is still an open question. It cannot catch this one,
//! because the person who never looked the record up writes no citation for it
//! to check. What is missing is a way to get **from a clause to the record**,
//! and that is what this file is.
//!
//! # Where the index lives, and why here
//!
//! The rendered index is in this module's docs, below, and is regenerated by
//! [`the_rendered_index_is_current`] — the test fails with the exact block to
//! paste whenever the ledger moves. Two reasons for a doc comment rather than a
//! generated file under `tests/fixtures/`:
//!
//! * a generated fixture would be gitignored like the other generated spec
//!   artifacts, and a gitignored artifact has no committed baseline to drift
//!   from, so it could not be a guard at all — only a `--check` gate over a
//!   *committed* artifact would work, and that is a second copy of this text
//!   with the same maintenance cost and less chance of being read;
//! * the reader this is for is holding a clause string, and a clause string is
//!   greppable from the repo root:
//!
//! ```text
//! grep -n 'delins.md:47' tests/it/clause_ruling_index.rs
//! ```
//!
//! **State the limit honestly**: this is a floor, not a solution. The person
//! reading `assets/hgvs-nomenclature/docs/recommendations/DNA/delins.md` gets no
//! signal at the point of reading. The submodule is upstream's checkout, so
//! nothing may be written into it; a repo-side index that a `grep` finds is the
//! best available placement, and the tests below are what keep it true.
//!
//! # Ranges: every citation is indexed per line
//!
//! The ledger spells some citations as ranges (`…/DNA/delins.md:79-84`,
//! `…/consultation/open-issues.md:77-78`) and others as single lines. Someone
//! who looked up `open-issues.md:78` must find the record that cites
//! `open-issues.md:77-78`, and vice versa, so **the index key is a single
//! `file:line`** and a range citation is expanded into one entry per line it
//! covers. The record's own spelling is preserved in the entry (`via
//! …:77-78`), so nothing is lost by the expansion.
//!
//! That is not hypothetical: `open-issues.md:78` is currently reached by an
//! exact citation from one record and by a range citation from another, and
//! those two records disagree in status. A file-granular or spelling-granular
//! index would have shown them as unrelated.
//!
//! # Counts measured on this base
//!
//! **Read them off the generated index below, not from this paragraph.** The
//! header line of that block is regenerated from the ledger, and
//! [`the_index_is_not_vacuous`] pins the same figures, so both move together and
//! neither can be quietly restated.
//!
