/// Refuses a citation whose range is implausibly wide.
///
/// A typo (`:5-500`) would otherwise silently expand into hundreds of index
/// keys and bury the real ones. No real citation is anywhere near this.
const MAX_RANGE_LINES: u32 = 64;

/// An index key: one spec file and one line in it.
///
/// Ordering is `(file, line)` with the line compared numerically, so
/// `duplication.md:26` sorts before `duplication.md:148` rather than after it.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Debug)]
struct ClauseLine {
    file: String,
    line: u32,
}

impl std::fmt::Display for ClauseLine {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}:{}", self.file, self.line)
    }
}

/// One record's claim on one clause line.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Debug)]
struct Claim {
    /// Sorted first so a clause line's records render alphabetically.
    id: String,
    status: String,
    role_label: &'static str,
    /// The record's own spelling, kept only when it differs from the key —
    /// i.e. when the citation was a range.
    via: Option<String>,
}

/// Expand one citation into the clause lines it covers.
///
/// `…/delins.md:47` yields one; `…/delins.md:79-84` yields six. The record's
/// spelling is returned alongside so the caller can annotate range-derived
/// entries.
fn expand(clause: &str) -> Vec<ClauseLine> {
    let (file, locator) = clause
        .rsplit_once(':')
        .unwrap_or_else(|| panic!("citation {clause} has no `:<line>` locator"));
    let parse = |s: &str| -> u32 {
        s.parse()
            .unwrap_or_else(|e| panic!("citation {clause}: `{s}` is not a line number: {e}"))
    };
    let (first, last) = match locator.split_once('-') {
        Some((first, last)) => (parse(first), parse(last)),
        None => {
            let only = parse(locator);
            (only, only)
        }
    };
    assert!(
        first > 0,
        "citation {clause} names line 0; source lines are 1-based, so no file carries it — and \
         both checks below accept it, since 0 <= 0 and a zero-width span is under the limit"
    );
    assert!(
        first <= last,
        "citation {clause} runs backwards ({first} > {last})"
    );
    assert!(
        last - first < MAX_RANGE_LINES,
        "citation {clause} spans {} lines, more than the {MAX_RANGE_LINES}-line sanity limit — \
         a range that wide is almost certainly a typo and would bury the rest of the index",
        last - first + 1
    );
    (first..=last)
        .map(|line| ClauseLine {
            file: file.to_string(),
            line,
        })
        .collect()
}

/// The whole index: clause line -> every record naming it.
fn build_index() -> BTreeMap<ClauseLine, BTreeSet<Claim>> {
    let mut index: BTreeMap<ClauseLine, BTreeSet<Claim>> = BTreeMap::new();
    for record in rulings::records() {
        for citation in &record.citations {
            let keys = expand(&citation.clause);
            let is_range = keys.len() > 1;
            for key in keys {
                index.entry(key).or_default().insert(Claim {
                    id: record.id.clone(),
                    status: record.status.clone(),
                    role_label: citation.role.label(),
                    via: is_range.then(|| citation.clause.clone()),
                });
            }
        }
    }
    index
}

/// One rendered `    \`id\` — status (role)` line.
///
/// Each claim gets its own line, and that is load-bearing rather than
/// cosmetic: `ruling_citation_currency.rs` judges a status word against every
/// record id on the *same* line, so putting two records with different statuses
/// on one line would make this file fail that scan.
fn render_claim(claim: &Claim) -> String {
    let via = match &claim.via {
        Some(clause) => format!(", via {clause}"),
        None => String::new(),
    };
    format!(
        "    `{}` — {} ({}{via})",
        claim.id, claim.status, claim.role_label
    )
}

fn render_entry(out: &mut String, key: &ClauseLine, claims: &BTreeSet<Claim>, mark_multi: bool) {
    let marker = if mark_multi && claims.len() > 1 {
        "  [MULTI]"
    } else {
        ""
    };
    let _ = writeln!(out, "{key}{marker}");
    for claim in claims {
        let _ = writeln!(out, "{}", render_claim(claim));
    }
}

/// The whole index as the text embedded in this module's docs.
fn render_index() -> String {
    let index = build_index();
    let records = rulings::records();
    let decided = records.iter().filter(|r| r.status == "decided").count();
    let undecided = records.len() - decided;
    let multi: Vec<(&ClauseLine, &BTreeSet<Claim>)> =
        index.iter().filter(|(_, c)| c.len() > 1).collect();

    let mut out = String::new();
    let _ = writeln!(out, "CLAUSE -> RECORD INDEX");
    let _ = writeln!(
        out,
        "{} records, {decided} decided / {undecided} undecided",
        records.len()
    );
    let _ = writeln!(
        out,
        "{} clause lines, of which {} are named by more than one record",
        index.len(),
        multi.len()
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "== every clause line ==");
    let _ = writeln!(out);
    for (key, claims) in &index {
        render_entry(&mut out, key, claims, true);
    }
    let _ = writeln!(out);
    let _ = writeln!(out, "== clause lines named by more than one record ==");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "-- mixed verdicts: at least one settled record and at least one still an --"
    );
    let _ = writeln!(
        out,
        "-- unanswered question on the same line. This is where re-derivation from --"
    );
    let _ = writeln!(
        out,
        "-- the spec text actually happens; read BOTH records before forming a view. --"
    );
    let _ = writeln!(out);
    let mixed = |claims: &BTreeSet<Claim>| {
        claims
            .iter()
            .map(|c| &c.status)
            .collect::<BTreeSet<_>>()
            .len()
            > 1
    };
    for (key, claims) in multi.iter().filter(|(_, c)| mixed(c)) {
        render_entry(&mut out, key, claims, false);
    }
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "-- same verdict across every record naming the line --"
    );
    let _ = writeln!(out);
    for (key, claims) in multi.iter().filter(|(_, c)| !mixed(c)) {
        render_entry(&mut out, key, claims, false);
    }
    out
}

/// The index block currently embedded in this module's docs.
fn embedded_index() -> String {
    let path = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(SELF_RELATIVE_PATH);
    let text =
        std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let mut inside = false;
    let mut block = String::new();
    for line in text.lines() {
        if line.contains(BEGIN_MARKER) {
            inside = true;
            continue;
        }
        if line.contains(END_MARKER) {
            inside = false;
            continue;
        }
        if !inside {
            continue;
        }
        let stripped = line.strip_prefix("//! ").unwrap_or(
            line.strip_prefix("//!")
                .unwrap_or_else(|| panic!("index block line is not a doc comment: {line}")),
        );
        // The block is wrapped in a `text` fence so rustdoc does not try to
        // compile or link it; the fences are not part of the index.
        if stripped.trim_start().starts_with("```") {
            continue;
        }
        block.push_str(stripped);
        block.push('\n');
    }
    block
}

/// The scan is not vacuous, and the counts are the measured ones.
///
/// Modelled on `ruling_citation_currency.rs`'s
/// `the_scan_reads_the_tree_it_claims_to`: an index built from a ledger that
/// failed to parse, or an expander that dropped every citation, would otherwise
/// make every assertion below pass trivially.
#[test]
fn the_index_is_not_vacuous() {
    let records = rulings::records();
    let decided = records.iter().filter(|r| r.status == "decided").count();
    let undecided = records.iter().filter(|r| r.status == "undecided").count();
    assert_eq!(
        (records.len(), decided, undecided),
        (24, 21, 3),
        "measured ledger census changed. If this is a real ledger change, update the module docs \
         and this pin together. Note the repo `CLAUDE.md` claims 8 records with 5 unanswered, \
         which was already wrong before this test existed"
    );
    assert_eq!(
        decided + undecided,
        records.len(),
        "a record carries a status that is neither `decided` nor `undecided`"
    );

    let index = build_index();
    assert!(
        index.len() >= 30,
        "only {} clause lines indexed — the expander or the ledger reader is broken",
        index.len()
    );
    // Every record must reach the index, or the inversion lost one.
    let indexed_ids: BTreeSet<&String> = index.values().flatten().map(|c| &c.id).collect();
    assert_eq!(
        indexed_ids.len(),
        records.len(),
        "{} of {} records reached the index",
        indexed_ids.len(),
        records.len()
    );
    // And the range expander must have actually expanded something, or the
    // range-handling contract in the module docs is untested.
    let via_range = index.values().flatten().filter(|c| c.via.is_some()).count();
    assert!(
        via_range > 0,
        "no range citation was expanded — the file-vs-line contract in this module's docs is \
         vacuous on this ledger"
    );
}

