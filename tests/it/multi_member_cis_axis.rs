//! The real-world multi-member cis alleles, as an axis (#1443, part 1).
//!
//! `canonicalize_from_sequence` is gated on `members.len() > 1`, so a
//! single-member input never reaches the partitioner, the changed-column bound
//! or the member-ordering rules. `examples/harvest_multi_member_cis.rs` swept
//! all four bulk corpora for inputs that do: **592 out of 9 949 738 rows**.
//! Those 592 are the entire real-world evidence base for that code path, and
//! before this module they lived only inside bulk corpora whose test suites
//! *skip green* when the fixtures are absent — and those corpora are not in the
//! git tree (they are release assets, fetched by
//! `scripts/fetch-test-fixtures.sh`), so on a checkout that had not fetched them
//! the evidence was silently invisible.
//!
//! The harvested fixture is committed, so this module runs everywhere.
//!
//! # Two tiers
//!
//! 1. **Always on.** Every row parses, and the distributions — members per
//!    allele, and the gap between consecutive members — are pinned. This is a
//!    description of what consumers of *observed* variants actually submit, and
//!    it is the number that motivates the generated corpus in
//!    `cis_confluence_axis`: separations are overwhelmingly large, which is
//!    exactly why real data cannot exercise a partitioner.
//! 2. **Manifest-gated** (`FERRO_MANIFEST`, or `benchmark-output/manifest.json`;
//!    skipped with a message when neither is present, the same convention
//!    `biocommons_normalize_tests` uses). Normalizes every row against real
//!    reference data and checks idempotence and sequence preservation, then
//!    censuses how often the spanning-`delins` respelling of a row converges to
//!    the same output.
//!
//! # Why the respelling census is a census
//!
//! Confluence over real rows does not hold today. Pinning the numbers documents
//! where it stands; asserting perfection would just leave the suite red. The
//! target is total convergence, and a move towards it is the welcome direction —
//! but every figure is pinned by **equality**, and the converged *rows* are
//! pinned alongside the count so a move in either direction names itself. See
//! [`CONVERGED_ROWS`]: "must only ever go up" is a statement about which
//! direction is good news, never a licence for the guard to pass quietly.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::{Arc, OnceLock};

use serde::Deserialize;

use ferro_hgvs::spdi::hgvs_to_spdi;
use ferro_hgvs::{
    parse_hgvs, HgvsVariant, MultiFastaProvider, NormalizeConfig, Normalizer, ReferenceProvider,
};

const FIXTURE_PATH: &str = "tests/fixtures/cis/multi_member_cis_alleles.json";

/// Reference bases fetched either side of a row's span, so a normalized output
/// that shifted still lands inside the window it is compared in.
const WINDOW_FLANK: u64 = 200;

/// Widest window worth fetching. A row spanning more than this is a structural
/// call whose bases are not the interesting part; fetching megabases to compare
/// them would dominate the run.
const MAX_WINDOW: u64 = 100_000;

// ---------------------------------------------------------------------------
// Fixture
// ---------------------------------------------------------------------------

#[derive(Deserialize)]
struct Row {
    input: String,
    /// The harvester's own member count, taken from the parsed allele. See
    /// [`the_harvested_member_census_is_unchanged`], which re-derives it from
    /// the string alone and pins that the two agree.
    members: usize,
}

#[derive(Deserialize)]
struct Fixture {
    rows_scanned: usize,
    rows: Vec<Row>,
}

fn fixture() -> &'static Fixture {
    static FIXTURE: OnceLock<Fixture> = OnceLock::new();
    FIXTURE.get_or_init(|| {
        let text = fs::read_to_string(FIXTURE_PATH)
            .unwrap_or_else(|e| panic!("failed to read {FIXTURE_PATH}: {e}"));
        serde_json::from_str(&text)
            .unwrap_or_else(|e| panic!("failed to parse {FIXTURE_PATH}: {e}"))
    })
}

// ---------------------------------------------------------------------------
// Syntax: members and the gaps between them
// ---------------------------------------------------------------------------

/// Split the contents of an allele's outer brackets on `;` **at depth zero**.
///
/// A naive `split(';')` over-counts, because an inserted-range payload carries
/// its own brackets and its own separator (`g.[a_bins[SEQ;c_d];e_finsAT]`).
///
/// This is deliberately a *second, independent* derivation of a figure the
/// harvester already records: the harvester gets its count from `parse_hgvs`,
/// and this one gets it from the string. Pinning that they agree
/// ([`the_harvested_member_census_is_unchanged`]) is what would catch the
/// fixture being regenerated by a selection rule that had drifted away from
/// what the parser sees.
fn split_members(inner: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut depth = 0i32;
    let mut start = 0usize;
    for (index, byte) in inner.bytes().enumerate() {
        match byte {
            b'[' | b'(' => depth += 1,
            b']' | b')' => depth -= 1,
            b';' if depth == 0 => {
                out.push(&inner[start..index]);
                start = index + 1;
            }
            _ => {}
        }
    }
    out.push(&inner[start..]);
    out
}

/// The `;`-separated members inside a row's outer brackets, bracket-aware.
fn members_of(input: &str) -> Vec<&str> {
    let (Some(open), Some(close)) = (input.find('['), input.rfind(']')) else {
        return Vec::new();
    };
    if close <= open {
        return Vec::new();
    }
    split_members(&input[open + 1..close])
}

/// The 1-based `(start, end)` a member names, when that is a pair of plain
/// integers.
///
/// `None` when the member carries an intronic offset (`453+625`), a UTR anchor
/// (`*17`, `-30`) or a non-numeric position. Deliberately so: the *distance*
/// between two such members is not a number that can be read off the string —
/// `c.100+50` and `c.101-50` may be thousands of bases apart or adjacent,
/// depending on the intron — and a census that guessed would be worse than one
/// that abstains and says how often it did.
fn plain_span(member: &str) -> Option<(u64, u64)> {
    // A member may carry its own coordinate prefix in a mixed allele
    // (`[c.1del;c.5del]`).
    let body = match member.as_bytes() {
        [_, b'.', ..] => &member[2..],
        _ => member,
    };
    let (start, rest) = leading_number(body)?;
    let end = match rest.strip_prefix('_') {
        Some(tail) => leading_number(tail)?.0,
        None => start,
    };
    Some((start, end))
}

/// A leading run of digits, rejected when it is followed by an offset marker.
fn leading_number(text: &str) -> Option<(u64, &str)> {
    let digits = text.bytes().take_while(u8::is_ascii_digit).count();
    if digits == 0 {
        return None;
    }
    let rest = &text[digits..];
    if rest.starts_with('+') || rest.starts_with('-') {
        return None;
    }
    text[..digits].parse().ok().map(|n| (n, rest))
}

/// Unchanged bases between two consecutive members, as a bucket label.
///
/// The buckets are what the generated corpus in `cis_confluence_axis` is a
/// deliberate complement to: it enumerates separations 0, 1, 2, 3, 5 and 8,
/// which is where a partitioner has a decision to make.
fn separation_bucket(previous_end: u64, next_start: u64) -> &'static str {
    if next_start <= previous_end {
        return "overlapping or unordered";
    }
    match next_start - previous_end - 1 {
        0 => "0 (adjacent)",
        1 => "1",
        2 => "2",
        3 => "3",
        4..=8 => "4-8",
        9..=99 => "9-99",
        100..=999 => "100-999",
        _ => "1000+",
    }
}

/// The gap census over every consecutive member pair in the fixture.
fn separation_census() -> BTreeMap<&'static str, usize> {
    let mut census = BTreeMap::new();
    for row in &fixture().rows {
        let members = members_of(&row.input);
        for pair in members.windows(2) {
            let bucket = match (plain_span(pair[0]), plain_span(pair[1])) {
                (Some((_, previous_end)), Some((next_start, _))) => {
                    separation_bucket(previous_end, next_start)
                }
                _ => "not readable from the string",
            };
            *census.entry(bucket).or_insert(0) += 1;
        }
    }
    census
}

