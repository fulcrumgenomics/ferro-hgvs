fn manifest_path() -> Option<PathBuf> {
    // Same convention as `biocommons_normalize_tests`: `FERRO_MANIFEST` is
    // authoritative when set, with a well-known fallback.
    if let Ok(path) = std::env::var("FERRO_MANIFEST") {
        let path = PathBuf::from(path);
        return path.exists().then_some(path);
    }
    let fallback = Path::new("benchmark-output/manifest.json");
    fallback.exists().then(|| fallback.to_path_buf())
}

fn provider() -> Option<Arc<MultiFastaProvider>> {
    static PROVIDER: OnceLock<Option<Arc<MultiFastaProvider>>> = OnceLock::new();
    PROVIDER
        .get_or_init(|| {
            // A missing manifest is the legitimate skip. A manifest that is
            // present but will not load is a misconfiguration, and reporting it
            // as a no-op skip would hide it.
            let path = manifest_path()?;
            Some(Arc::new(
                MultiFastaProvider::from_manifest(&path)
                    .unwrap_or_else(|e| panic!("from_manifest({}) failed: {e}", path.display())),
            ))
        })
        .clone()
}

/// What the gated run found. Pinned as a baseline; see the module docs.
#[derive(Debug, Default, PartialEq, Eq)]
struct AxisCensus {
    rows: usize,
    /// Rows normalization declined or panicked on.
    declined: usize,
    /// Rows whose output is not its own normalized form.
    not_idempotent: usize,
    /// Rows whose reference window could not be assembled — a member with no
    /// SPDI triple, members on different sequences, or a span wider than
    /// [`MAX_WINDOW`]. Counted so "0 sequence changes" cannot quietly mean
    /// "nothing was checked".
    unwindowed: usize,
    /// Rows whose normalized output denotes a different sequence than the input.
    sequence_changed: usize,
    /// Rows whose spanning-`delins` respelling could be built at all.
    respellable: usize,
    /// … of those, the ones that normalize to the same string as the row.
    respelling_converged: usize,
}

/// A description's SPDI triples, all on one sequence, or `None`.
fn triples_of<P: ReferenceProvider + ?Sized>(
    provider: &P,
    descriptor: &str,
) -> Option<Vec<(String, u64, String, String)>> {
    let members: Vec<HgvsVariant> = match parse_hgvs(descriptor).ok()? {
        HgvsVariant::Allele(allele) => allele.variants.clone(),
        single => vec![single],
    };
    let mut triples = Vec::with_capacity(members.len());
    for member in &members {
        let triple = hgvs_to_spdi(member, provider).ok()?;
        triples.push((
            triple.sequence.clone(),
            triple.position,
            triple.deletion.clone(),
            triple.insertion.clone(),
        ));
    }
    let first = triples.first()?.0.clone();
    triples.iter().all(|t| t.0 == first).then_some(triples)
}

/// Apply triples inside a fetched window, the same 3'→5' walk as
/// `common::cis_apply_oracle::apply_reason` but with window-relative offsets.
fn apply_in_window(
    window: &str,
    window_start: u64,
    triples: &[(String, u64, String, String)],
) -> Option<String> {
    let mut ordered: Vec<&(String, u64, String, String)> = triples.iter().collect();
    ordered.sort_by_key(|t| (std::cmp::Reverse(t.1), std::cmp::Reverse(t.2.len())));
    let bytes = window.as_bytes();
    let mut edited = bytes.to_vec();
    let mut claimed = window.len();
    let mut insertion_at: Option<usize> = None;
    for (_, position, deletion, insertion) in ordered {
        let start = usize::try_from(position.checked_sub(window_start)?).ok()?;
        let end = start.checked_add(deletion.len())?;
        if end > window.len() || end > claimed {
            return None;
        }
        if deletion.is_empty() && insertion_at == Some(start) {
            return None;
        }
        if !bytes[start..end].eq_ignore_ascii_case(deletion.as_bytes()) {
            return None;
        }
        edited.splice(start..end, insertion.bytes());
        if deletion.is_empty() {
            insertion_at = Some(start);
        }
        claimed = start;
    }
    String::from_utf8(edited).ok()
}

/// The window a set of triples needs, plus the bases in it.
fn window_for<P: ReferenceProvider + ?Sized>(
    provider: &P,
    triples: &[(String, u64, String, String)],
) -> Option<(u64, String)> {
    let sequence = &triples.first()?.0;
    let lo = triples.iter().map(|t| t.1).min()?;
    let hi = triples.iter().map(|t| t.1 + t.2.len() as u64).max()?;
    if hi.saturating_sub(lo) > MAX_WINDOW {
        return None;
    }
    let start = lo.saturating_sub(WINDOW_FLANK);
    let end = hi + WINDOW_FLANK;
    let bases = provider.get_sequence(sequence, start, end).ok()?;
    // A window truncated at the end of the sequence still starts where we asked.
    Some((start, bases))
}

/// The spanning-`delins` respelling of a row, when its members name plain
/// positions on one axis.
///
/// Deliberately narrow. The union of two members carrying intronic offsets is
/// not a contiguous span in the coordinate system they are written in, so there
/// is no honest single-`delins` spelling of it; rows like that are counted as
/// not respellable rather than respelled wrongly.
fn spanning_respelling(
    input: &str,
    window: &str,
    window_start: u64,
    triples: &[(String, u64, String, String)],
) -> Option<String> {
    let (accession, axis) = input.split_once(':')?;
    let axis_prefix = axis.get(..2)?;
    if !axis_prefix.ends_with('.') {
        return None;
    }
    let members = members_of(input);
    if members.len() < 2 {
        return None;
    }
    // Every member must name plain positions, and none may be a pure insertion:
    // an insertion's written positions straddle its junction, so the union of a
    // set including one does not line up with the union of the SPDI spans.
    let mut low = u64::MAX;
    let mut high = 0u64;
    for member in &members {
        let (start, end) = plain_span(member)?;
        if member.contains("ins") && !member.contains("delins") {
            return None;
        }
        low = low.min(start);
        high = high.max(end);
    }
    let spdi_low = triples.iter().map(|t| t.1).min()?;
    let spdi_high = triples.iter().map(|t| t.1 + t.2.len() as u64).max()?;
    // The written span and the SPDI span must describe the same number of
    // bases, or the two coordinate frames do not correspond and the respelling
    // would be nonsense.
    if spdi_high.checked_sub(spdi_low)? != high.checked_sub(low)? + 1 {
        return None;
    }

    let applied = apply_in_window(window, window_start, triples)?;
    let prefix = usize::try_from(spdi_low - window_start).ok()?;
    let suffix = window
        .len()
        .checked_sub(usize::try_from(spdi_high - window_start).ok()?)?;
    if applied.len() < prefix + suffix {
        return None;
    }
    let alt = &applied[prefix..applied.len() - suffix];
    if alt.is_empty() {
        return Some(format!("{accession}:{axis_prefix}{low}_{high}del"));
    }
    Some(format!("{accession}:{axis_prefix}{low}_{high}delins{alt}"))
}

/// Measure the census, and return the *inputs* of the rows that converged.
///
/// The row list is not a debugging aid, it is half the guard: see
/// [`CONVERGED_ROWS`]. A census of seven integers cannot distinguish `+19` from
/// `+20 −1`, so the set has to be carried out of the measurement alongside the
/// count.
fn measure_axis(provider: &Arc<MultiFastaProvider>) -> (AxisCensus, Vec<String>) {
    let normalizer = Normalizer::with_config(provider.clone(), NormalizeConfig::default());
    let mut census = AxisCensus::default();
    let mut converged_rows = Vec::new();

    for row in &fixture().rows {
        census.rows += 1;
        let Ok(variant) = parse_hgvs(&row.input) else {
            census.declined += 1;
            continue;
        };
        let normalized = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
            normalizer.normalize(&variant)
        }));
        let Ok(Ok(output)) = normalized else {
            census.declined += 1;
            continue;
        };
        let output = output.to_string();

        // Idempotence: the output must be its own normalized form.
        let again = parse_hgvs(&output).ok().and_then(|v| {
            std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| normalizer.normalize(&v)))
                .ok()
                .and_then(|r| r.ok())
                .map(|v| v.to_string())
        });
        if again.as_deref() != Some(output.as_str()) {
            census.not_idempotent += 1;
        }

        // Sequence preservation, over a window both descriptions fit in.
        let (Some(input_triples), Some(output_triples)) = (
            triples_of(provider.as_ref(), &row.input),
            triples_of(provider.as_ref(), &output),
        ) else {
            census.unwindowed += 1;
            continue;
        };
        let combined: Vec<_> = input_triples
            .iter()
            .chain(output_triples.iter())
            .cloned()
            .collect();
        let Some((window_start, window)) = window_for(provider.as_ref(), &combined) else {
            census.unwindowed += 1;
            continue;
        };
        let from_input = apply_in_window(&window, window_start, &input_triples);
        let from_output = apply_in_window(&window, window_start, &output_triples);
        match (from_input, from_output) {
            (Some(before), Some(after)) if before == after => {}
            (None, _) => census.unwindowed += 1,
            _ => census.sequence_changed += 1,
        }

        // The spanning respelling, where one exists.
        let Some(respelling) =
            spanning_respelling(&row.input, &window, window_start, &input_triples)
        else {
            continue;
        };
        census.respellable += 1;
        let respelled = parse_hgvs(&respelling).ok().and_then(|v| {
            std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| normalizer.normalize(&v)))
                .ok()
                .and_then(|r| r.ok())
                .map(|v| v.to_string())
        });
        if respelled.as_deref() == Some(output.as_str()) {
            census.respelling_converged += 1;
            converged_rows.push(row.input.clone());
        }
    }

    (census, converged_rows)
}

/// The pinned gated census, measured against a prepared reference.
///
/// How to read it. **0 declined**: the harvester selects on `parse_hgvs`, so
/// every row parses, and the normalizer declines none of them. **96 unwindowed**
/// are rows whose members do not all resolve to SPDI triples on one sequence, or
/// whose span is wider than [`MAX_WINDOW`]; they are counted rather than skipped
/// so `sequence_changed: 0` cannot quietly mean "nothing was checked".
///
/// The two numbers worth arguing about are the last pair: of **461** rows whose
/// spanning-`delins` respelling can be built at all, **395 (86%)** normalize to
/// the same string as the row itself, and 66 do not. That 86% is the real-data
/// counterpart to the 59% `cis_confluence_axis` measures over designed alleles,
/// and the gap between them is the point of this issue: real rows are easy
/// because their members are far apart (see
/// [`the_separation_census_is_unchanged`]), so they do not exercise the
/// partitioner that the designed corpus does.
///
/// `not_idempotent` and `sequence_changed` are asserted at zero on their own
/// before the comparison, so a regression there names itself rather than
/// surfacing as a moved tuple. Every field here is pinned by **equality**,
/// including `respelling_converged` — see [`CONVERGED_ROWS`] for why this is
/// deliberately not a ratchet.
///
/// # A rise is not by itself a licence to re-bless
///
/// [`CONVERGED_ROWS`] records that a rise here is "good news to be re-blessed
/// and declared". That is the common case, not the universal one, and this
/// section is the exception it does not cover.
///
/// A rise reads as progress and is the thing this constant exists to protect,
/// which makes it the easiest number in the suite to move for the wrong reason.
/// Two spellings converge when they reach one string; that string can be one
/// **neither of them asserted**, produced by re-partitioning the block from the
/// sequence across bases the input left unchanged (`general.md:34`). Convergence
/// bought that way is a defect wearing the shape of a fix, and it will show up
/// here as `respelling_converged` going up with nothing else moving.
///
/// This is not hypothetical: an experimental partitioner arm moved this figure
/// by five while leaving `rows`, `declined`, `not_idempotent`, `unwindowed`,
/// `sequence_changed` and `respellable` all unchanged — which is exactly the
/// signature described above.
///
/// So before raising it: name the classes that moved, and the clause that
/// carried each. If they cannot be named individually, the rise is a
/// re-derivation and the constant stays where it is while the cause is found.
///
/// # Raised 395 -> 401 by #1649, and this section's test applied
///
/// The rise has the exact signature the section above warns about — every other
/// field is unchanged, `respellable` included — so it is discharged here rather
/// than asserted. The six rows are named in [`CONVERGED_ROWS`]'s own history and
/// **all six are two-deletion cis pairs**:
///
/// ```text
/// NM_001110792.2:c.[1076_1102del;1124_1142del]   NM_001110792.2:c.[859_907del;934_941del]
/// NM_001282426.2:c.[391_397del;456_468del]       NM_004992.3:c.[1155_1200del;987_988del]
/// NM_005144.5:c.[1258del;1263_1283del]           NM_130838.2:c.[255_259del;269del]
/// ```
///
/// That is the mechanism, not a coincidence to be waved at: #1649 lets `merge`'s
/// payload splitter express *deletion, retained reference, deletion*, the mirror
/// of the two-insertion shape it already expressed, and the rows that move are
/// exactly the ones carrying that shape. **0 rows stopped converging**, so this
/// is `+6 −0` rather than a net figure hiding a swap — which is the distinction
/// [`CONVERGED_ROWS`] exists to make visible.
///
/// The clause is `general.md:34` read through `canonical-form-choice-when-both-legal`
/// (`decided`): the partition is re-derived from the **resulting sequence** and
/// what falls out is emitted. So the finer partition is not an extra liberty
/// taken with the input's unchanged bases — it is what the sequence supports and
/// what the splitter previously could not spell. `sequence_changed` staying **0**
/// across all 592 rows is the check that no member was lost buying it.
