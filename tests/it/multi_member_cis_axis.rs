/// Every harvested row is a multi-member cis allele the parser accepts.
///
/// This is an assertion of zero, not a pinned split, because the harvester
/// *decides* with `parse_hgvs`: a row is written to the fixture only if it
/// parses as an `AllelePhase::Cis` allele with more than one member. So the
/// fixture's 592 rows are 592 pieces of evidence about the partitioner, with
/// nothing to discount.
///
/// It reached that state by dropping 58 rows a purely syntactic selection had
/// admitted, in two groups:
///
/// * **46 malformed corpus strings** ferro rejects by design — substitutions run
///   together with no separator (`c.[1327G>T;1727G>C2002C>T]`), a member
///   repeating the coordinate prefix (`c.[652C>T;c.940A>G]`), methylation edits
///   (`gom`/`lom`). They are real ClinVar rows and they are worth having as
///   *parser* evidence, but they never reach `canonicalize_from_sequence`, so
///   they were never evidence about this code path.
/// * **12 rows that are not alleles at all** — a single variant whose
///   inserted-range payload happens to carry a `;`
///   (`g.80114186_80114187ins[80114172_80114186;NC_000020.11:g.2823027_2826302;AAA]`),
///   which a `find('[')..rfind(']')` scan reads as a member list.
///
/// A failure here is therefore one of two things, and the message says which:
/// the fixture is stale against a parser that has changed, or it was
/// regenerated by a selection rule that no longer matches the parser.
/// Re-harvest (`cargo run --features dev --example harvest_multi_member_cis`)
/// and review what moved.
#[test]
fn the_harvested_rows_parse_as_multi_member_alleles() {
    let mut accepted = 0usize;
    let mut wrong_shape = Vec::new();
    for row in &fixture().rows {
        match parse_hgvs(&row.input) {
            Ok(HgvsVariant::Allele(allele)) if allele.variants.len() > 1 => {
                accepted += 1;
                assert_eq!(
                    allele.variants.len(),
                    row.members,
                    "{}: recorded {} members, parses as {}",
                    row.input,
                    row.members,
                    allele.variants.len()
                );
            }
            Ok(_) => wrong_shape.push(format!(
                "{}: parses, but not as a multi-member allele",
                row.input
            )),
            Err(e) => wrong_shape.push(format!("{}: {e}", row.input)),
        }
    }
    println!("harvested rows: {accepted} multi-member alleles");
    assert!(
        wrong_shape.is_empty(),
        "{} harvested rows are not multi-member alleles. The harvester selects \
         on `parse_hgvs`, so this means the fixture is stale against the parser \
         or was regenerated by a different rule:\n{}",
        wrong_shape.len(),
        wrong_shape.join("\n")
    );
    assert_eq!(accepted, 592, "harvested multi-member cis alleles");
}

/// The harvest's own census, pinned. Regenerating the fixture against different
/// corpora moves these, and that is a review-visible event rather than a silent
/// one.
#[test]
fn the_harvested_member_census_is_unchanged() {
    let fixture = fixture();
    assert_eq!(fixture.rows_scanned, 9_949_738, "corpus rows scanned");
    assert_eq!(
        fixture.rows.len(),
        592,
        "multi-member cis alleles harvested"
    );

    let mut census: BTreeMap<usize, usize> = BTreeMap::new();
    for row in &fixture.rows {
        *census.entry(row.members).or_insert(0) += 1;
    }
    assert_eq!(
        census,
        BTreeMap::from([(2, 561), (3, 22), (4, 6), (6, 3)]),
        "members per harvested allele, as the parser counted them"
    );

    // The same census re-derived from the strings alone, by a depth-aware split
    // that owes nothing to the parser. The two agree on every row — including
    // `LRG_501:g.[...ins[SEQ;a_b]...]`, whose payload `;` a naive `split(';')`
    // counts as a fourth member. That agreement is the point: it is what would
    // fail if the fixture were ever regenerated by a selection rule that had
    // drifted from what `parse_hgvs` sees.
    let mut bracket_aware: BTreeMap<usize, usize> = BTreeMap::new();
    for row in &fixture.rows {
        *bracket_aware
            .entry(members_of(&row.input).len())
            .or_insert(0) += 1;
    }
    assert_eq!(
        bracket_aware, census,
        "a depth-aware recount from the string disagrees with the harvester's \
         parsed member count"
    );
}

/// The distribution this whole issue rests on: in observed data, two changes in
/// one allele are almost never close enough to share a block.
///
/// If this census ever shifts towards the small buckets, the argument for the
/// generated corpus weakens and the argument for testing against real data
/// strengthens — so it is worth failing on.
#[test]
fn the_separation_census_is_unchanged() {
    let census = separation_census();
    println!("inter-member separations: {census:?}");
    assert_eq!(
        census,
        BTreeMap::from([
            ("0 (adjacent)", 24),
            ("1", 14),
            ("2", 17),
            ("3", 13),
            ("4-8", 38),
            ("9-99", 107),
            ("100-999", 163),
            ("1000+", 98),
            ("not readable from the string", 83),
            ("overlapping or unordered", 81),
        ]),
        "the inter-member separation distribution moved"
    );

    // The whole argument for a generated corpus, in one line: of 638 member
    // pairs, **106** are within eight bases of each other — the range where a
    // partitioner has a decision to make — and 261 are a hundred or more bases
    // apart. `cis_confluence_axis` generates 11 280 classes concentrated in
    // exactly that first bucket, which no amount of observed data supplies.
    let close: usize = ["0 (adjacent)", "1", "2", "3", "4-8"]
        .iter()
        .map(|bucket| census[bucket])
        .sum();
    assert_eq!(close, 106, "member pairs within eight bases of each other");
    assert_eq!(census.values().sum::<usize>(), 638, "member pairs censused");
}

