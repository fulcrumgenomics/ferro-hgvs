// ---------------------------------------------------------------------------
// The synthetic references
// ---------------------------------------------------------------------------

/// 256 bases of period-4 `ACGT` on either side of a core, so the base
/// immediately 5' of the core is `T` and the one immediately 3' of it is `A`.
/// Shared with `dump_normalized_corpus` and `tests/it/common/synthetic.rs`.
const PAD_OFFSET: usize = 256;

/// The genomic contig a `g.` class is drawn against.
const GENOMIC_CONTIG: &str = "NC_TEST.1";
/// The transcript a `c.` class is drawn against.
const TX_ACCESSION: &str = "NM_TEST.1";
/// The transcript an `n.` or `r.` class is drawn against. A separate accession
/// from [`TX_ACCESSION`] because it carries no CDS, which is what makes it a
/// non-coding transcript rather than a coding one addressed without its CDS.
const NR_ACCESSION: &str = "NR_TEST.1";
/// The contig the synthetic transcript is placed on.
const TX_CONTIG: &str = "chr_synth";

/// Core length. Long enough for four members separated by eight unchanged bases
/// with eight-base payloads, which is the widest design enumerated below.
const CORE_LEN: usize = 64;

/// CDS of the synthetic transcript, 1-based inclusive. The transcript sequence
/// *is* the core, and `CDS_START == 1` makes `c.p` the core's 1-based position
/// `p`, so a `g.` and a `c.` class over one design address the same bases. A
/// one-base 3'UTR is left over so the CDS is not the whole transcript.
const CDS_START: u64 = 1;
const CDS_END: u64 = 63;

/// The 0-based core offset every design starts at. Leaving eight bases of core
/// 5' of the first member gives a 5'-shifting member somewhere to travel that is
/// still inside the core, so a shifted respelling is not forced into the pad.
const DESIGN_START: usize = 8;

/// Highest 0-based core index a design may reference. Bounded by the `c.` axis:
/// index 63 is `c.*1`, and keeping every design inside the CDS means the two
/// axes enumerate exactly the same design set.
const MAX_INDEX: usize = CDS_END as usize - 1;

/// How far either way [`equivalent_placements`] looks for an equivalent
/// placement of a single member. A shift longer than this would have to travel
/// most of the core.
const SHIFT_SEARCH: isize = 20;

/// Member counts enumerated. Two is the smallest allele that reaches the
/// partitioner at all; four is where the bulk corpora run out of evidence
/// entirely (part 1 found seven three-member and three four-member rows).
const MEMBER_COUNTS: &[usize] = &[2, 3, 4];

/// Unchanged bases between consecutive members. Zero is adjacency — members
/// that share a block with nothing between them — and eight is far enough that
/// no partitioner should merge them.
const SEPARATIONS: &[usize] = &[0, 1, 2, 3, 5, 8];

/// Payload sizes: the deleted / inserted / duplicated length of a member.
const PAYLOADS: &[usize] = &[1, 2, 4, 8];

// ---------------------------------------------------------------------------
// Axes
// ---------------------------------------------------------------------------

/// A coordinate system a design can be written against.
///
/// The four differ in three ways and only three: which accession and prefix a
/// spelling carries, how far into its reference the core sits, and which
/// alphabet its bases are spelled in. Everything else — the layout, the
/// payloads, the equivalent-placement search, the applier — is axis-blind and
/// works in DNA over the core.
#[derive(Clone, Copy, PartialEq, Eq, Debug, PartialOrd, Ord)]
enum Axis {
    /// `g.` over a padded synthetic contig.
    Genome,
    /// `c.` over a coding transcript whose CDS starts at base 1.
    Cds,
    /// `n.` over a non-coding transcript.
    Tx,
    /// `r.` over the same non-coding transcript, spelled in lowercase RNA.
    Rna,
}

/// Every axis, in the order a corpus lists them.
const ALL_AXES: [Axis; 4] = [Axis::Genome, Axis::Cds, Axis::Tx, Axis::Rna];

/// The axes generated when `--axes` is not given. Deliberately *not* all of
/// them: `tests/it/cis_confluence_axis.rs` pins an exact census over this
/// corpus, so widening the default would move every pinned number.
const DEFAULT_AXES: &str = "g,c";

impl Axis {
    /// The HGVS prefix, which is also the `axis` field of an emitted class.
    fn label(self) -> &'static str {
        match self {
            Axis::Genome => "g",
            Axis::Cds => "c",
            Axis::Tx => "n",
            Axis::Rna => "r",
        }
    }

    fn from_label(label: &str) -> Option<Self> {
        ALL_AXES.into_iter().find(|axis| axis.label() == label)
    }

    fn accession(self) -> &'static str {
        match self {
            Axis::Genome => GENOMIC_CONTIG,
            Axis::Cds => TX_ACCESSION,
            Axis::Tx | Axis::Rna => NR_ACCESSION,
        }
    }

    /// The 0-based interbase offset of the core within this axis's reference,
    /// which is what an SPDI position has to have subtracted to become
    /// core-relative.
    fn offset(self) -> usize {
        match self {
            Axis::Genome => PAD_OFFSET,
            _ => 0,
        }
    }

    /// 0-based core index to 1-based axis position.
    fn pos(self, index: usize) -> usize {
        self.offset() + index + 1
    }

    /// Spell DNA bases in this axis's alphabet. Only `r.` differs: lowercase,
    /// with `u` for `t`.
    fn spell(self, bases: &str) -> String {
        match self {
            Axis::Rna => bases
                .chars()
                .map(|base| match base.to_ascii_lowercase() {
                    't' => 'u',
                    other => other,
                })
                .collect(),
            _ => bases.to_string(),
        }
    }

    /// The provider a class on this axis is drawn against, and the full
    /// sequence its coordinates address.
    fn reference(self, core: &str) -> (MockProvider, String) {
        match self {
            Axis::Genome => (genomic_provider(core), padded(core)),
            Axis::Cds => (coding_provider(core), core.to_string()),
            Axis::Tx | Axis::Rna => (noncoding_provider(core), core.to_string()),
        }
    }
}

