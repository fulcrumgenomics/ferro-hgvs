    /// `r.` is the only axis whose spelling alphabet differs, and getting it
    /// wrong is silent: a `t` in an `r.` payload would be rejected by the
    /// parser and dropped by the ground-truth filter, leaving a thinner corpus
    /// rather than a failure. So the alphabet is asserted directly.
    #[test]
    fn an_rna_spelling_is_lowercase_over_acgu() {
        assert_eq!(Axis::Rna.spell("ACGT"), "acgu");
        assert_eq!(Axis::Tx.spell("ACGT"), "ACGT");
        let corpus = build_corpus_on(1, &[Axis::Rna]);
        assert!(!corpus.classes.is_empty());
        for class in &corpus.classes {
            for spelling in &class.spellings {
                let (_, body) = spelling
                    .split_once(":r.")
                    .unwrap_or_else(|| panic!("{spelling} is not an r. description"));
                let bases: String = body.chars().filter(|c| c.is_ascii_alphabetic()).collect();
                assert!(
                    !bases.contains(['t', 'T']),
                    "{spelling} spells an RNA base as thymine"
                );
                assert!(
                    !bases.chars().any(|c| c.is_ascii_uppercase()),
                    "{spelling} spells an RNA base in upper case"
                );
            }
        }
    }

