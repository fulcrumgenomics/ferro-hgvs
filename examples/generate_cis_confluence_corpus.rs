fn render_member(axis: Axis, core: &str, member: &Member) -> String {
    let p = |index: usize| axis.pos(index);
    let last = member.start + member.span.saturating_sub(1);
    let payload = axis.spell(&member.payload);
    match member.kind {
        Kind::Del if member.span == 1 => format!("{}del", p(member.start)),
        Kind::Del => format!("{}_{}del", p(member.start), p(last)),
        Kind::Dup if member.span == 1 => format!("{}dup", p(member.start)),
        Kind::Dup => format!("{}_{}dup", p(member.start), p(last)),
        Kind::Sub => format!(
            "{}{}>{}",
            p(member.start),
            axis.spell(&core[member.start..member.start + 1]),
            payload
        ),
        Kind::Delins if member.span == 1 => {
            format!("{}delins{payload}", p(member.start))
        }
        Kind::Delins => format!("{}_{}delins{payload}", p(member.start), p(last)),
        // An insertion at interbase `start` sits between the bases at
        // `start - 1` and `start`.
        Kind::Ins => format!("{}_{}ins{payload}", p(member.start - 1), p(member.start)),
    }
}

fn render_allele(axis: Axis, core: &str, members: &[Member]) -> String {
    let rendered: Vec<String> = members
        .iter()
        .map(|m| render_member(axis, core, m))
        .collect();
    format!(
        "{}:{}.[{}]",
        axis.accession(),
        axis.label(),
        rendered.join(";")
    )
}

/// Render an arbitrary `(position, deletion, insertion)` triple in core
/// coordinates, choosing the plainest spelling its shape admits. Used for a
/// member that has been shifted off the placement its authored kind described,
/// where the original kind may no longer apply.
fn render_triple(axis: Axis, position: usize, deletion: &str, insertion: &str) -> Option<String> {
    let p = |index: usize| axis.pos(index);
    let inserted = axis.spell(insertion);
    match (deletion.is_empty(), insertion.is_empty()) {
        (true, true) => None,
        (true, false) => {
            if position == 0 {
                return None;
            }
            Some(format!("{}_{}ins{inserted}", p(position - 1), p(position)))
        }
        (false, true) if deletion.len() == 1 => Some(format!("{}del", p(position))),
        (false, true) => Some(format!(
            "{}_{}del",
            p(position),
            p(position + deletion.len() - 1)
        )),
        (false, false) if deletion.len() == 1 => Some(format!("{}delins{inserted}", p(position))),
        (false, false) => Some(format!(
            "{}_{}delins{inserted}",
            p(position),
            p(position + deletion.len() - 1)
        )),
    }
}

